"""Isolated acceptance smoke tests; all generated dependencies live in /tmp."""

import contextlib
import importlib.util
import io
import json
import shutil
import tempfile
import unittest
from pathlib import Path

from openpyxl import Workbook


ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("check_judgment", ROOT / "tools/check_judgment.py")
checker = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(checker)


class CheckJudgmentTest(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        for folder in ("schema", "outputs/judgment_v0", "outputs/gina_review_round1", "cases/toy"):
            (self.root / folder).mkdir(parents=True)
        shutil.copyfile(ROOT / "schema/judgment_contract.json", self.root / "schema/judgment_contract.json")
        (self.root / "cases/toy/input.json").write_text(json.dumps({"sequence": "ACDE"}))
        evidence_dir = self.root / "outputs/gina_review_round1"
        (evidence_dir / "case_sources.json").write_text(json.dumps({"TOY_CPMG": "toy"}))
        workbook = Workbook()
        workbook.active.title = "Evidence_rows"
        workbook.create_sheet("Appendix_rows")
        for sheet in workbook:
            sheet.append(["ID", "Source", "Protein (RelaxDB entry)"])
        workbook["Evidence_rows"].append(["TOY-r1", "toy", "TOY_CPMG (homolog)"])
        workbook["Evidence_rows"].append(["OTHER-r1", "toy", "OTHER_CPMG"])
        workbook["Appendix_rows"].append(["TOY-a1", "toy", "TOY_CPMG"])
        workbook.save(evidence_dir / "RelaxDB_CPMG_evidence_round1.xlsx")
        workbook.close()

    def run_fixture(self, fixture, args):
        directory = self.root / "outputs/judgment_v0"
        shutil.copyfile(ROOT / "tests/fixtures_judgment" / fixture, directory / "TOY_CPMG.json")
        stdout, stderr = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            status = checker.main(args, root=self.root)
        lines = stdout.getvalue().splitlines()
        self.assertEqual(len(lines), 1)
        result = json.loads(lines[0])
        self.assertEqual(set(result), {"entry", "pass", "n_judgments", "errors"})
        self.assertEqual(result, json.loads((directory / "TOY_CPMG.check.json").read_text()))
        self.assertEqual(result["entry"], "TOY_CPMG")
        self.assertEqual(result["n_judgments"], 3)
        return status, result, [json.loads(line) for line in stderr.getvalue().splitlines()]

    def test_passing_file_and_warnings(self):
        status, result, warnings = self.run_fixture("passing.json", ["TOY_CPMG"])
        self.assertEqual(status, 0)
        self.assertTrue(result["pass"])
        self.assertEqual(result["errors"], [])
        self.assertEqual({item["warning"]["kind"] for item in warnings}, {"weak_dynamic_evidence"})
        # Default discovery must ignore the report generated by the first run.
        status, result, _ = self.run_fixture("passing.json", [])
        self.assertEqual(status, 0)
        self.assertTrue(result["pass"])

    def test_failing_file_all_error_kinds(self):
        status, result, _ = self.run_fixture("failing.json", [])
        self.assertEqual(status, 3)
        self.assertFalse(result["pass"])
        self.assertEqual({error["kind"] for error in result["errors"]}, {
            "schema", "evidence_missing", "evidence_unknown_id", "evidence_wrong_protein",
            "residue_out_of_range", "window_missing", "conflict_mismatch", "summary_missing",
            "global_kex_assignment",
        })
        for error in result["errors"]:
            self.assertEqual(set(error), {"judgment_id", "kind", "detail"})
        details = [error["detail"] for error in result["errors"] if error["kind"] == "conflict_mismatch"]
        for expected in ("Unknown conflicting judgment", "different time_window", "no residues_entry overlap"):
            self.assertTrue(any(expected in detail for detail in details), expected)


if __name__ == "__main__":
    unittest.main()
